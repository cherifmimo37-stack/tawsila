
-- TAW S I L A | Initial PostgreSQL Schema
-- Safe: creates tables only if they do not exist.
-- Does not delete or migrate database.json.

BEGIN;

CREATE TABLE IF NOT EXISTS tawsila_customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(120) NOT NULL,
    phone VARCHAR(20) NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS tawsila_drivers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(120) NOT NULL,
    phone VARCHAR(20) NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    car VARCHAR(100) NOT NULL,
    plate VARCHAR(40) NOT NULL,
    approval_status VARCHAR(20) NOT NULL DEFAULT 'pending'
        CHECK (approval_status IN ('pending', 'approved', 'rejected', 'suspended')),
    is_online BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS tawsila_rides (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT REFERENCES tawsila_customers(id) ON DELETE SET NULL,
    driver_id BIGINT REFERENCES tawsila_drivers(id) ON DELETE SET NULL,
    customer_name VARCHAR(120) NOT NULL,
    customer_phone VARCHAR(20) NOT NULL,
    pickup TEXT NOT NULL,
    destination TEXT NOT NULL,
    price NUMERIC(12,2) NOT NULL DEFAULT 0,
    distance_km NUMERIC(10,2) NOT NULL DEFAULT 0,
    pickup_location JSONB,
    destination_coords JSONB,
    status VARCHAR(20) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'accepted', 'started', 'completed', 'cancelled')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS tawsila_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT REFERENCES tawsila_customers(id) ON DELETE CASCADE,
    driver_id BIGINT REFERENCES tawsila_drivers(id) ON DELETE CASCADE,
    token_hash CHAR(64) NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (
        (customer_id IS NOT NULL AND driver_id IS NULL)
        OR
        (customer_id IS NULL AND driver_id IS NOT NULL)
    )
);

CREATE INDEX IF NOT EXISTS idx_tawsila_rides_status
ON tawsila_rides(status);

CREATE INDEX IF NOT EXISTS idx_tawsila_rides_driver
ON tawsila_rides(driver_id);

COMMIT;
